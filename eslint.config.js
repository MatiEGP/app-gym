// https://docs.expo.dev/guides/using-eslint/
const fs = require('node:fs');
const path = require('node:path');
const { defineConfig } = require('eslint/config');
const expoConfig = require('eslint-config-expo/flat');
const eslintPluginPrettierRecommended = require('eslint-plugin-prettier/recommended');

// ---------------------------------------------------------------------------
// Architecture boundaries (AGENTS.md → Architecture Rules), enforced with the core
// `no-restricted-imports` rule. Tests: eslint.config.test.js.
// ESLint does not merge options of the same rule across config blocks, so every
// block below carries the complete list of patterns for its files.
// ---------------------------------------------------------------------------

// Planned features plus any folder that exists under src/features.
const PLANNED_FEATURES = [
  'workout-session',
  'routines',
  'exercises',
  'history',
  'settings',
  'auth',
];
const featuresDir = path.join(__dirname, 'src', 'features');
const existingFeatures = fs.existsSync(featuresDir)
  ? fs
      .readdirSync(featuresDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
  : [];
const FEATURES = [...new Set([...PLANNED_FEATURES, ...existingFeatures])];

const noClimbing = {
  regex: '^(\\.\\./){2,}',
  message: 'Do not climb more than one folder with relative imports; use the "@/" alias.',
};

const dataAccessModules = [
  'drizzle-orm',
  'drizzle-orm/**',
  'expo-sqlite',
  'expo-sqlite/**',
  '@supabase/**',
  '@/shared/db',
  '@/shared/db/**',
  '@/shared/sync',
  '@/shared/sync/**',
];

const domainForbidden = {
  group: [
    'react',
    'react/**',
    'react-native',
    'react-native/**',
    'expo',
    'expo/**',
    'expo-*',
    'expo-*/**',
    '@expo/**',
    ...dataAccessModules,
  ],
  message: 'domain/ is pure TypeScript: no React, Expo, Drizzle, Supabase, or data access imports.',
};

const uiForbidden = {
  group: [...dataAccessModules, '@/features/*/infrastructure', '@/features/*/infrastructure/**'],
  message: 'ui/ never touches the DB or Supabase; call a use case from application/ instead.',
};

const uiNoOwnInfrastructure = {
  regex: '^\\.\\./infrastructure(/|$)',
  message: 'ui/ never touches the DB or Supabase; call a use case from application/ instead.',
};

const otherFeaturesMessage = 'Import other features only through their application/ layer.';

// Gitignore-style groups cannot re-include a path whose parent is excluded, so the bare
// feature root ("@/features/x") is matched by a separate regex instead of "@/features/*".
function otherFeaturesForbidden(feature) {
  return [
    {
      group: [
        '@/features/*/**',
        '!@/features/*/application',
        '!@/features/*/application/**',
        `!@/features/${feature}/**`,
      ],
      message: otherFeaturesMessage,
    },
    { regex: `^@/features/(?!${feature}$)[^/]+$`, message: otherFeaturesMessage },
  ];
}

const restrict = (...patterns) => ({ 'no-restricted-imports': ['error', { patterns }] });

const boundaries = [
  { files: ['src/**/*.{js,jsx,ts,tsx}'], rules: restrict(noClimbing) },
  ...FEATURES.flatMap((feature) => {
    const base = `src/features/${feature}`;
    const otherFeatures = otherFeaturesForbidden(feature);
    return [
      { files: [`${base}/**/*.{js,jsx,ts,tsx}`], rules: restrict(noClimbing, ...otherFeatures) },
      {
        files: [`${base}/domain/**/*.{js,jsx,ts,tsx}`],
        rules: restrict(noClimbing, ...otherFeatures, domainForbidden),
      },
      {
        files: [`${base}/ui/**/*.{js,jsx,ts,tsx}`],
        rules: restrict(noClimbing, ...otherFeatures, uiForbidden, uiNoOwnInfrastructure),
      },
    ];
  }),
];

module.exports = defineConfig([
  expoConfig,
  eslintPluginPrettierRecommended,
  ...boundaries,
  {
    // Root-level tooling files run in Node (CommonJS).
    files: ['*.js'],
    languageOptions: {
      sourceType: 'commonjs',
      globals: { __dirname: 'readonly', __filename: 'readonly' },
    },
  },
  {
    // Tooling tests run in the Jest "tooling" project.
    files: ['*.test.js'],
    languageOptions: {
      globals: { describe: 'readonly', it: 'readonly', expect: 'readonly' },
    },
  },
  {
    // Generated by Expo; not committed.
    ignores: ['dist/*', '.expo/*', 'expo-env.d.ts', 'src/shared/db/migrations/*'],
  },
]);
